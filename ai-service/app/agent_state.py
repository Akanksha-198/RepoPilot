from typing import TypedDict


class AgentState(TypedDict, total=False):

    # ==================================================
    # USER REQUEST
    # ==================================================

    user_request: str

    # ==================================================
    # REPOSITORY
    # ==================================================

    repository_name: str
    repository_path: str

    # ==================================================
    # TASK UNDERSTANDING
    # ==================================================

    task_understanding: str

    # ==================================================
    # RETRIEVED CODE
    # ==================================================

    retrieved_sources: list[dict]

    # ==================================================
    # ANALYSIS
    # ==================================================

    analysis: str

    # ==================================================
    # PLAN
    # ==================================================

    plan: list[str]
    approved: bool

    # ==================================================
    # PROPOSED CHANGES
    # ==================================================

    proposed_changes: list[dict]

    # ==================================================
    # DIFF
    # ==================================================

    diff: str

    # ==================================================
    # CHANGE APPROVAL
    # ==================================================

    change_approved: bool

    # ==================================================
    # CHANGE RESULT
    # ==================================================

    change_result: dict

    # ==================================================
    # VALIDATION
    # ==================================================

    validation_result: dict
    

    # ==================================================
    # FAILURE ANALYSIS
    # ==================================================

    failure_analysis: str
    
    repair_proposal: dict
    repair_diff: str
    repair_result: dict
    repair_approved: bool


    # ==================================================
    # FINAL RESULT
    # ==================================================

    final_summary: str

    # ==================================================
    # TASK HISTORY
    # ==================================================

    task_history: dict